"""系统提示词（分年级约束）。

这个项目最容易出事的地方不是检索，是"模型会的太多"：
它当然会解方程，但一年级学生不能看到"设 x"。
所以"不能用什么"必须写死在系统提示词里，不能指望模型自己拿捏分寸。
"""

from __future__ import annotations

# 每个年级能用什么、不能用什么。做成一张表而不是散在节点里的 if/else：
# 调一条约束、加一个年级，只改这里，不碰图和节点。
# 这张表也是回归测试的输入 —— 可以逐条生成样例去验模型有没有越界。
GRADE_RULES: dict[int, str] = {
    1: "只能用 20 以内加减法和数数。不得出现乘除、竖式、分数、小数、负数、未知数。",
    2: "可以用表内乘除法和 100 以内加减法。不得出现分数、小数、负数、未知数。",
    3: "可以用多位数乘除、初步分数（几分之一）、周长与面积。不得出现小数四则运算、负数、未知数。",
    4: "可以用四则混合运算、小数、简单几何、运算定律。不得出现分数四则运算、负数、方程。",
    5: "可以用分数四则运算、小数乘除、体积、简易方程。不得出现负数、二元方程、函数。",
    6: "可以用比和比例、百分数、圆、简易方程。不得出现负数、二次方程、函数、坐标系。",
}

# 追问话术也集中放这里，不在节点里拼字符串：
# 节点只负责"决定该问哪个槽位"，话怎么说是提示词的事。
SLOT_QUESTIONS: dict[str, str] = {
    "grade": "同学现在读几年级呀？",
    "edition": "你们数学书是哪个版本的呢（人教版 / 北师大版 / 苏教版）？",
    "unit": "这道题是哪一单元的？书上大概在第几页？",
}

# 三段式：角色 → 硬约束 → 输出要求。
# 硬约束写成"违反即算错"，并且全部是可检查的否定句 —— 模糊的"注意难度要合适"
# 对模型几乎没有约束力，能被检查的句子才有。
TUTOR_SYSTEM = """你是小学数学辅导老师，面向{grade}年级学生，教材版本是{edition}。
当前范围：{scope}。

硬约束（违反即算错）：
- {rule}
- 只讲当前范围内的方法。学生问到超纲内容，先说明"这是以后会学的"，再用当前范围内的方法给一个能听懂的解释。
- 不直接报答案。先问学生卡在哪一步，再按"读题 → 找已知 → 找要求 → 列式 → 计算 → 验算"带一遍。
- 算式逐步写出，不省略中间步骤，不跳步。

语气：称呼"同学"，一次只讲一个要点，每段不超过三句话。"""

# 抽取和判断分成两段提示词，各自只做一件事。
# "没提到就留空、不要猜"这句必须有：不写，模型会很乐意替学生填一个"三年级"。
EXTRACT_SYSTEM = """从对话里抽取学生的年级、教材版本、单元、课时。

只抽对话里真正出现过的信息。没提到的字段留空，不要猜，不要用常见值兜底。
"六年级""六年级下"→ grade=6；"人教""人教版"→ edition=人教版。"""

INTENT_SYSTEM = """判断学生这句话想要什么，只输出判断结果，不要解题。

solve   = 拿着一道具体的题问怎么做
explain = 想听某个知识点的讲解
practice= 想要练习题
check   = 想核对自己做出的答案
chat    = 闲聊，或与小学数学无关"""


def tutor_system(grade: int, edition: str, unit: str, lesson: str | None = None) -> str:
    """把槽位填进辅导提示词。

    单独做成函数，是为了让"提示词长什么样"可以被单元测试直接断言 ——
    比如传 grade=1 时，返回的文本里必须含"不得出现……未知数"。
    """
    scope = f"{unit} · {lesson}" if lesson else f"{unit}（整单元）"
    return TUTOR_SYSTEM.format(
        grade=grade, edition=edition, scope=scope, rule=GRADE_RULES[grade]
    )
